-- Student-facing features: rule-based homework suggestions, reports, shared
-- resources, native polls, lost-and-found notices, and short-lived input state.

ALTER TABLE bot_chat_settings
    ADD COLUMN IF NOT EXISTS homework_autocollect_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS homework_approver_role TEXT NOT NULL DEFAULT 'class_leader'
        CHECK (homework_approver_role IN ('class_leader', 'moderator', 'admin')),
    ADD COLUMN IF NOT EXISTS schedule_changes_enabled BOOLEAN NOT NULL DEFAULT FALSE;

-- Keep moderation roles in bot_chat_members.role and add academic roles without
-- forcing one person to choose between being a class leader and a moderator.
CREATE TABLE IF NOT EXISTS bot_chat_member_roles (
    chat_id BIGINT NOT NULL REFERENCES bot_chat_settings(chat_id) ON DELETE CASCADE,
    telegram_id BIGINT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('class_leader')),
    assigned_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (chat_id, telegram_id, role)
);
CREATE INDEX IF NOT EXISTS idx_bot_chat_member_roles_role
    ON bot_chat_member_roles(chat_id, role);

CREATE TABLE IF NOT EXISTS bot_subject_aliases (
    chat_id BIGINT NOT NULL REFERENCES bot_chat_settings(chat_id) ON DELETE CASCADE,
    alias TEXT NOT NULL,
    canonical_subject TEXT NOT NULL,
    added_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (chat_id, alias),
    CHECK (length(trim(alias)) BETWEEN 2 AND 120),
    CHECK (length(trim(canonical_subject)) BETWEEN 2 AND 160)
);

CREATE TABLE IF NOT EXISTS bot_homework_candidates (
    chat_id BIGINT NOT NULL REFERENCES bot_chat_settings(chat_id) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_message_id INTEGER NOT NULL,
    source_author_telegram_id BIGINT,
    source_hash TEXT NOT NULL,
    subject TEXT NOT NULL,
    description TEXT NOT NULL,
    source_excerpt TEXT NOT NULL,
    due_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected', 'expired')),
    reviewed_by BIGINT,
    homework_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL DEFAULT now() + interval '7 days',
    PRIMARY KEY (chat_id, id),
    UNIQUE (chat_id, source_message_id),
    CHECK (length(trim(source_excerpt)) <= 1200)
);
CREATE INDEX IF NOT EXISTS idx_bot_homework_candidates_pending
    ON bot_homework_candidates(chat_id, created_at)
    WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS idx_bot_homework_candidates_expiry
    ON bot_homework_candidates(expires_at)
    WHERE status = 'pending';
CREATE UNIQUE INDEX IF NOT EXISTS idx_bot_homework_candidates_pending_hash
    ON bot_homework_candidates(chat_id, source_hash)
    WHERE status = 'pending';

CREATE TABLE IF NOT EXISTS bot_homework_attachments (
    chat_id BIGINT NOT NULL,
    homework_id BIGINT NOT NULL,
    telegram_file_id TEXT NOT NULL,
    telegram_file_unique_id TEXT NOT NULL,
    file_name TEXT,
    mime_type TEXT,
    file_size BIGINT CHECK (file_size IS NULL OR file_size >= 0),
    added_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (chat_id, homework_id, telegram_file_unique_id),
    FOREIGN KEY (chat_id, homework_id)
        REFERENCES bot_homework(chat_id, id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS bot_chat_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL REFERENCES bot_chat_settings(chat_id) ON DELETE CASCADE,
    reporter_telegram_id BIGINT NOT NULL,
    target_telegram_id BIGINT,
    message_id INTEGER,
    category TEXT NOT NULL DEFAULT 'other'
        CHECK (category IN ('spam', 'harassment', 'unsafe', 'other')),
    reason TEXT,
    status TEXT NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'resolved', 'dismissed')),
    handled_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_bot_chat_reports_open
    ON bot_chat_reports(chat_id, created_at DESC)
    WHERE status = 'open';

CREATE TABLE IF NOT EXISTS bot_group_resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL REFERENCES bot_chat_settings(chat_id) ON DELETE CASCADE,
    subject TEXT,
    title TEXT NOT NULL CHECK (length(trim(title)) BETWEEN 2 AND 160),
    url TEXT NOT NULL CHECK (length(trim(url)) BETWEEN 8 AND 2048),
    added_by BIGINT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_bot_group_resources_chat
    ON bot_group_resources(chat_id, is_active, subject);

CREATE TABLE IF NOT EXISTS bot_group_polls (
    chat_id BIGINT NOT NULL REFERENCES bot_chat_settings(chat_id) ON DELETE CASCADE,
    message_id INTEGER NOT NULL,
    poll_id TEXT NOT NULL,
    question TEXT NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (chat_id, message_id),
    UNIQUE (poll_id)
);

CREATE TABLE IF NOT EXISTS bot_lost_found (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL REFERENCES bot_chat_settings(chat_id) ON DELETE CASCADE,
    kind TEXT NOT NULL CHECK (kind IN ('lost', 'found')),
    title TEXT NOT NULL CHECK (length(trim(title)) BETWEEN 3 AND 160),
    details TEXT NOT NULL CHECK (length(trim(details)) BETWEEN 3 AND 1200),
    contact_telegram_id BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'resolved', 'removed')),
    expires_at TIMESTAMPTZ NOT NULL DEFAULT now() + interval '30 days',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_bot_lost_found_active
    ON bot_lost_found(chat_id, created_at DESC)
    WHERE status = 'active';

-- Form inputs are short-lived and contain only the current step's small payload.
CREATE TABLE IF NOT EXISTS bot_user_flows (
    chat_id BIGINT NOT NULL,
    telegram_id BIGINT NOT NULL,
    flow TEXT NOT NULL,
    step TEXT NOT NULL,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    expires_at TIMESTAMPTZ NOT NULL DEFAULT now() + interval '15 minutes',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (chat_id, telegram_id)
);
CREATE INDEX IF NOT EXISTS idx_bot_user_flows_expiry
    ON bot_user_flows(expires_at);

CREATE TABLE IF NOT EXISTS bot_user_daily_digests (
    telegram_id BIGINT NOT NULL,
    local_date DATE NOT NULL,
    sent_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (telegram_id, local_date)
);

CREATE TABLE IF NOT EXISTS bot_schedule_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id UUID NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    change_key TEXT NOT NULL UNIQUE,
    change_kind TEXT NOT NULL CHECK (change_kind IN ('room_changed', 'teacher_changed', 'class_cancelled')),
    starts_at TIMESTAMPTZ NOT NULL,
    subject TEXT NOT NULL,
    old_room TEXT,
    new_room TEXT,
    old_teacher TEXT,
    new_teacher TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_bot_schedule_changes_group_created
    ON bot_schedule_changes(group_id, created_at DESC);

CREATE TABLE IF NOT EXISTS bot_schedule_change_deliveries (
    change_id BIGINT NOT NULL REFERENCES bot_schedule_changes(id) ON DELETE CASCADE,
    recipient_kind TEXT NOT NULL CHECK (recipient_kind IN ('private', 'group')),
    recipient_id BIGINT NOT NULL,
    sent_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (change_id, recipient_kind, recipient_id)
);

-- Only message hashes and counts are retained; message bodies are never stored.
CREATE TABLE IF NOT EXISTS bot_chat_spam_seen (
    chat_id BIGINT NOT NULL REFERENCES bot_chat_settings(chat_id) ON DELETE CASCADE,
    author_telegram_id BIGINT NOT NULL,
    text_hash TEXT NOT NULL,
    occurrences INTEGER NOT NULL DEFAULT 1 CHECK (occurrences > 0),
    window_started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (chat_id, author_telegram_id, text_hash)
);
CREATE INDEX IF NOT EXISTS idx_bot_chat_spam_seen_last
    ON bot_chat_spam_seen(last_seen_at);
