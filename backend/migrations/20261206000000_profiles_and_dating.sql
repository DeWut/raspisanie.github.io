-- Private account preferences and an explicitly opt-in, adult-only matching feature.

CREATE TABLE IF NOT EXISTS bot_user_profiles (
    telegram_id BIGINT PRIMARY KEY REFERENCES users(telegram_id) ON DELETE CASCADE,
    display_name TEXT NOT NULL CHECK (length(trim(display_name)) BETWEEN 2 AND 48),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS bot_dating_profiles (
    telegram_id BIGINT PRIMARY KEY REFERENCES users(telegram_id) ON DELETE CASCADE,
    display_name TEXT NOT NULL CHECK (length(trim(display_name)) BETWEEN 2 AND 48),
    bio TEXT NOT NULL DEFAULT '' CHECK (length(bio) <= 280),
    tags TEXT[] NOT NULL DEFAULT '{}',
    age_confirmed_at TIMESTAMPTZ,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_paused BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_bot_dating_profiles_discovery
    ON bot_dating_profiles(updated_at DESC)
    WHERE age_confirmed_at IS NOT NULL AND is_active=TRUE AND is_paused=FALSE;

CREATE TABLE IF NOT EXISTS bot_dating_swipes (
    from_telegram_id BIGINT NOT NULL REFERENCES bot_dating_profiles(telegram_id) ON DELETE CASCADE,
    to_telegram_id BIGINT NOT NULL REFERENCES bot_dating_profiles(telegram_id) ON DELETE CASCADE,
    action TEXT NOT NULL CHECK (action IN ('like','pass')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (from_telegram_id,to_telegram_id),
    CHECK (from_telegram_id <> to_telegram_id)
);

CREATE TABLE IF NOT EXISTS bot_dating_matches (
    user1_telegram_id BIGINT NOT NULL REFERENCES bot_dating_profiles(telegram_id) ON DELETE CASCADE,
    user2_telegram_id BIGINT NOT NULL REFERENCES bot_dating_profiles(telegram_id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','ended')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ended_at TIMESTAMPTZ,
    PRIMARY KEY (user1_telegram_id,user2_telegram_id),
    CHECK (user1_telegram_id < user2_telegram_id)
);

CREATE TABLE IF NOT EXISTS bot_dating_blocks (
    blocker_telegram_id BIGINT NOT NULL REFERENCES bot_dating_profiles(telegram_id) ON DELETE CASCADE,
    blocked_telegram_id BIGINT NOT NULL REFERENCES bot_dating_profiles(telegram_id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (blocker_telegram_id,blocked_telegram_id),
    CHECK (blocker_telegram_id <> blocked_telegram_id)
);

CREATE TABLE IF NOT EXISTS bot_dating_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_telegram_id BIGINT NOT NULL REFERENCES users(telegram_id) ON DELETE CASCADE,
    target_telegram_id BIGINT NOT NULL REFERENCES users(telegram_id) ON DELETE CASCADE,
    category TEXT NOT NULL CHECK (category IN ('spam','inappropriate','underage','other')),
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','reviewed','dismissed')),
    handled_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (reporter_telegram_id <> target_telegram_id)
);
CREATE INDEX IF NOT EXISTS idx_bot_dating_reports_open
    ON bot_dating_reports(created_at DESC) WHERE status='open';
